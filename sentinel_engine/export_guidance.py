"""Exports sample guidance packets for the blueprint/AR demo page, so the page
works from a plain file with no server. Run:
    .venv/bin/python -m sentinel_engine.export_guidance
Writes demo/src/ar/sample-packets.js (an ES module; regenerate after engine changes).
Everything exported is simulated and carries the engine's candidate/approval flags."""
from __future__ import annotations

import json
import sys
from pathlib import Path

from fastapi.testclient import TestClient

from .api import create_app

OUTPUT_PATH = Path(__file__).resolve().parent.parent / "demo" / "src" / "ar" / "sample-packets.js"

BLOCK = {"hazard_type": "blocked", "text": "west stairwell", "default_floor": "F2",
         "verified": True, "source": "responder_report",
         "description": "radio report: west stairwell blocked"}


def collect_scenes() -> list[dict]:
    client = TestClient(create_app())
    seed = client.post("/demo/scenario", json={"block_west_stairwell": False}).json()
    unit, civ = seed["responder_id"], seed["civilian_id"]
    scenes = [
        {"id": "responder-initial", "persona": "responder",
         "title": "Firefighter → Studio 210",
         "subtitle": "Initial candidate route. Fire and smoke reported in the east corridor (F2).",
         "packet": client.get(f"/guidance/responder/{unit}").json()},
        {"id": "civilian-initial", "persona": "civilian",
         "title": "Occupant → nearest exit",
         "subtitle": "Evacuation route drafted for the Studio 210 report, pending command approval.",
         "packet": client.get(f"/guidance/civilian/{civ}").json()},
    ]
    client.post("/hazards", json=BLOCK)
    scenes += [
        {"id": "responder-reroute", "persona": "responder",
         "title": "Firefighter → Studio 210 (rerouted)",
         "subtitle": "West stairwell reported blocked. Route recomputed via the east stairwell; "
                     "it passes an unverified fire report and needs command review.",
         "packet": client.get(f"/guidance/responder/{unit}").json()},
        {"id": "civilian-reroute", "persona": "civilian",
         "title": "Occupant → nearest exit (rerouted)",
         "subtitle": "With the west stairwell blocked, the only exit route passes the east corridor hazard.",
         "packet": client.get(f"/guidance/civilian/{civ}").json()},
    ]
    return scenes


def main(path: Path = OUTPUT_PATH) -> int:
    scenes = collect_scenes()
    for scene in scenes:
        scene["packet"]["generated_at"] = "sample"   # keep the export reproducible
    body = json.dumps(scenes, indent=1).replace("<", "\\u003c")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("// Generated by `python -m sentinel_engine.export_guidance` — do not edit.\n"
                    "// Sample guidance packets from the engine's demo scenario. All simulated.\n"
                    f"export const SAMPLE_SCENES = {body};\n")
    print(f"wrote {path} ({len(scenes)} scenes, {path.stat().st_size // 1024} KB)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
